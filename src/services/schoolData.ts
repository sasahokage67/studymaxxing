export const getSavedSchools = (): School[] => {
  const saved = localStorage.getItem('lp_schools');
  if (saved) {
    try {
      const parsed = JSON.parse(saved);
      if (Array.isArray(parsed)) {
        return [...parsed, ...SEEDED_KZ_SCHOOLS];
      }
    } catch (e) {
      console.error(e);
    }
  }
  return SEEDED_KZ_SCHOOLS;
};

export const saveCustomSchool = (schoolData: { name: string; city: string; website: string }): School => {
  const newSchool: School = {
    id: `sch_custom_${Date.now()}`,
    name: schoolData.name.trim(),
    city: schoolData.city.trim() || 'Казахстан',
    website: schoolData.website.trim() || '',
    isCustom: true
  };

  const saved = localStorage.getItem('lp_schools');
  let currentCustom: School[] = [];
  if (saved) {
    try {
      currentCustom = JSON.parse(saved);
    } catch (e) {
      console.error(e);
    }
  }

  const updated = [newSchool, ...currentCustom];
  localStorage.setItem('lp_schools', JSON.stringify(updated));
  return newSchool;
};
